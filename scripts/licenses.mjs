// Writes docs/DEPENDENCIES.md: every runtime dependency (shipped to users) and dev dependency with its license.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const ALLOWED = /^(MIT|ISC|Apache-2\.0|BSD-2-Clause|BSD-3-Clause|0BSD|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0|CC-BY-4\.0|MPL-2\.0)$/;

function info(name) {
  const p = join(root, 'node_modules', name, 'package.json');
  if (!existsSync(p)) return { version: '?', license: '?' };
  const j = JSON.parse(readFileSync(p, 'utf8'));
  return { version: j.version, license: typeof j.license === 'string' ? j.license : j.license?.type ?? 'UNKNOWN' };
}

const rows = (deps) => Object.keys(deps ?? {}).sort().map((n) => ({ name: n, ...info(n) }));
const runtime = rows(pkg.dependencies);
const dev = rows(pkg.devDependencies);

// Every transitive package in the lock file, for the audit summary.
const all = Object.entries(lock.packages ?? {}).filter(([k]) => k.startsWith('node_modules/')).map(([k, v]) => ({ name: k.replace(/^.*node_modules\//, ''), license: v.license ?? 'UNKNOWN', dev: !!v.dev }));
const counts = {};
for (const p of all) counts[p.license] = (counts[p.license] ?? 0) + 1;
const flagged = all.filter((p) => !p.dev && !ALLOWED.test(String(p.license).replace(/[()]/g, '').split(/ OR | AND /)[0]));

const table = (list) => ['| Package | Version | License |', '|---|---|---|', ...list.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`)].join('\n');
const md = `# Dependencies and licenses

Generated by \`npm run licenses\` on ${new Date().toISOString().slice(0, 10)}. All are open source; nothing requires payment.

## Shipped to users (runtime)

${table(runtime)}

| Why | |
|---|---|
| react, react-dom | UI framework (MIT) |
| dexie | IndexedDB wrapper with versioned migrations and live queries (Apache-2.0) |
| tesseract.js + core + @tesseract.js-data/eng | Local OCR in WebAssembly; self-hosted, no CDN (Apache-2.0 / MIT for the model package) |
| fflate | ZIP compression for the XLSX writer (MIT) |
| jspdf, jspdf-autotable | PDF reports, loaded only when exporting (MIT) |

Charts are hand-written SVG (no library). Encryption uses the browser's built-in Web Crypto API.

## Development and testing only

${table(dev)}

## Transitive license audit (${all.length} packages in the lock file)

${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`).join('\n')}

Runtime packages outside the permissive allow-list: ${flagged.length ? flagged.map((f) => `${f.name} (${f.license})`).join(', ') : 'none'}.
`;
writeFileSync(join(root, 'docs', 'DEPENDENCIES.md'), md);
console.log(`docs/DEPENDENCIES.md written (${runtime.length} runtime, ${dev.length} dev, ${all.length} total; flagged: ${flagged.length})`);
if (flagged.length) process.exitCode = 1;
